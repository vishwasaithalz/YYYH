export const CheatsheetsView: React.FC<CheatsheetsViewProps> = ({
  onBackToArticles,
  onNavigateTools,
  onSelectArticleUrl
}) => {
  const [selectedCategory, setSelectedCategory] = useState<string>('All');
  const [searchQuery, setSearchQuery] = useState<string>('');
  const [copiedId, setCopiedId] = useState<string | null>(null);

  const categories = ['All', 'Linux Hardening', 'Nmap Scanning', 'Wireshark Filters', 'Active Directory', 'Subnetting & CIDR'];

  const handleCopy = (text: string, id: string) => {
    navigator.clipboard.writeText(text);
    setCopiedId(id);
    setTimeout(() => setCopiedId(null), 2000);
  };

  const filteredItems = useMemo(() => {
    return CHEAT_ITEMS.filter(item => {
      if (selectedCategory !== 'All' && item.category !== selectedCategory) {
        return false;
      }
      if (!searchQuery.trim()) return true;
      const q = searchQuery.toLowerCase().trim();
      return (
        item.title.toLowerCase().includes(q) ||
        item.command.toLowerCase().includes(q) ||
        item.description.toLowerCase().includes(q) ||
        item.tags.some(t => t.toLowerCase().includes(q))
      );
    });
  }, [selectedCategory, searchQuery]);

  return (
    <div id="cheatsheets-main-view" className="space-y-6 max-w-7xl lg:max-w-[1360px] w-full mx-auto px-4 sm:px-6 py-3">
      {/* Header Navigation Bar */}
      <div className="flex flex-wrap items-center justify-between gap-4 border-b border-slate-800 pb-4">
        {onBackToArticles && (
          <button
            onClick={onBackToArticles}
            className="text-xs font-mono text-emerald-400 hover:text-emerald-300 flex items-center gap-1.5 cursor-pointer bg-slate-900/60 border border-emerald-900/40 px-3 py-1.5 rounded"
          >
            <ArrowLeft className="w-3.5 h-3.5" />
            <span>&larr; Back to Security Feed</span>
          </button>
        )}
        <div className="flex items-center gap-2">
          {onNavigateTools && (
            <button
              onClick={onNavigateTools}
              className="text-xs font-mono text-cyan-400 hover:text-cyan-300 flex items-center gap-1.5 cursor-pointer bg-slate-900/60 border border-cyan-900/40 px-3 py-1.5 rounded"
            >
              <Terminal className="w-3.5 h-3.5" />
              <span>Launch Live Tools Suite &rarr;</span>
            </button>
          )}
        </div>
      </div>

      {/* Hero Banner */}
      <div className="rounded-xl border border-emerald-900/40 bg-gradient-to-br from-[#090d16] via-[#0d1424] to-[#090d16] p-6 sm:p-8 relative overflow-hidden">
        <div className="absolute -right-12 -bottom-12 w-64 h-64 bg-emerald-500/5 rounded-full blur-3xl pointer-events-none" />
        <div className="max-w-3xl space-y-3 relative z-10">
          <div className="inline-flex items-center gap-2 px-2.5 py-1 rounded bg-emerald-950/80 border border-emerald-800/60 text-emerald-400 text-xs font-mono">
            <BookOpen className="w-3.5 h-3.5" />
            <span>OPERATIONAL FIELD MANUAL</span>
          </div>
          <h1 className="text-2xl sm:text-3xl font-bold font-mono text-white tracking-tight">
            Interactive Ethical Hacking &amp; Sysadmin Cheatsheets
          </h1>
          <p className="text-slate-300 text-sm sm:text-base leading-relaxed">
            Instant command syntax, cryptographic parameters, network inspection filters, and defensive kernel tuning configurations. Field-tested by YinYangYoHackers researchers.
          </p>
        </div>
      </div>

      {/* Filter and Search Bar */}
      <div className="flex flex-col md:flex-row items-stretch md:items-center justify-between gap-4 bg-slate-900/80 border border-slate-800 p-4 rounded-xl">
        <div className="flex items-center gap-1.5 overflow-x-auto pb-2 md:pb-0 scrollbar-none">
          {categories.map(cat => (
            <button
              key={cat}
              onClick={() => setSelectedCategory(cat)}
              className={`px-3 py-1.5 rounded text-xs font-mono whitespace-nowrap transition-all cursor-pointer ${
                selectedCategory === cat
                  ? 'bg-emerald-600 text-white font-bold shadow-md shadow-emerald-950'
                  : 'bg-slate-800/70 text-slate-400 hover:text-slate-200 hover:bg-slate-800'
              }`}
            >
              {cat}
            </button>
          ))}
        </div>

        <div className="relative min-w-[240px]">
          <Search className="w-4 h-4 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2" />
          <input
            type="text"
            value={searchQuery}
            onChange={(e) => setSearchQuery(e.target.value)}
            placeholder="Search commands, flags, tools..."
            className="w-full bg-slate-950 border border-slate-800 rounded-lg pl-9 pr-4 py-2 text-xs font-mono text-slate-200 placeholder:text-slate-500 focus:outline-none focus:border-emerald-500"
          />
        </div>
      </div>

      {/* Cheatsheet Cards Grid */}
      <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
        {filteredItems.map(item => (
          <div
            key={item.id}
            className="rounded-xl border border-slate-800 bg-[#070b14] p-5 flex flex-col justify-between space-y-4 hover:border-slate-700 transition-all shadow-sm"
          >
            <div>
              <div className="flex items-center justify-between gap-2 mb-2">
                <span className="text-[11px] font-mono uppercase tracking-wider text-emerald-400 font-semibold bg-emerald-950/60 border border-emerald-900/40 px-2 py-0.5 rounded">
                  {item.category}
                </span>
                <span className="text-[11px] font-mono text-slate-500">
                  {item.id}
                </span>
              </div>
              <h2 className="text-base font-bold text-white mb-2 font-mono">
                {item.title}
              </h2>
              <p className="text-xs text-slate-400 leading-relaxed">
                {item.description}
              </p>
            </div>

            {/* Code / Command Block */}
            <div className="relative group bg-slate-950 border border-slate-800/90 rounded-lg p-3.5 font-mono text-xs text-emerald-300">
              <pre className="overflow-x-auto whitespace-pre-wrap pr-10 font-mono text-[12px] leading-relaxed select-all">
                {item.command}
              </pre>
              <button
                onClick={() => handleCopy(item.command, item.id)}
                title="Copy command to clipboard"
                className="absolute right-2 top-2 p-1.5 rounded bg-slate-900 border border-slate-700 hover:border-emerald-500 text-slate-400 hover:text-emerald-400 transition-colors cursor-pointer"
              >
                {copiedId === item.id ? (
                  <Check className="w-4 h-4 text-emerald-400" />
                ) : (
                  <Copy className="w-4 h-4" />
                )}
              </button>
            </div>

            {/* Tag Pills */}
            <div className="flex flex-wrap gap-1.5 pt-1">
              {item.tags.map(tag => (
                <span
                  key={tag}
                  className="text-[10px] font-mono px-2 py-0.5 rounded bg-slate-900 text-slate-400 border border-slate-800"
                >
                  #{tag}
                </span>
              ))}
            </div>
          </div>
        ))}
      </div>

      {/* Common Ports Quick Table Section */}
      <section className="mt-12 pt-8 border-t border-slate-800">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 mb-6">
          <div>
            <h2 className="text-lg font-bold font-mono text-white flex items-center gap-2">
              <Network className="w-4 h-4 text-cyan-400" />
              <span>Standard Recon Ports Quick Reference</span>
            </h2>
            <p className="text-xs text-slate-400 mt-1">
              Key ports, associated protocols, attack vectors, and automated nmap probes.
            </p>
          </div>
        </div>

        <div className="overflow-x-auto rounded-xl border border-slate-800 bg-[#070b14]">
          <table className="w-full text-left text-xs font-mono text-slate-300">
            <thead className="bg-slate-950 border-b border-slate-800 text-slate-400 uppercase text-[11px]">
              <tr>
                <th className="py-3 px-4">Port</th>
                <th className="py-3 px-4">Protocol &amp; Service</th>
                <th className="py-3 px-4">Common Vulnerability</th>
                <th className="py-3 px-4">Reconnaissance Probe</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-800/60">
              {commonPortsData.slice(0, 8).map(port => (
                <tr key={port.port} className="hover:bg-slate-900/40 transition-colors">
                  <td className="py-3 px-4 text-emerald-400 font-bold whitespace-nowrap">
                    {port.port}/{port.protocol}
                  </td>
                  <td className="py-3 px-4 text-white font-medium">
                    {port.service}
                  </td>
                  <td className="py-3 px-4 text-slate-400 text-[11px] max-w-xs">
                    {port.vulnerabilities}
                  </td>
                  <td className="py-3 px-4 text-cyan-300 text-[11px] max-w-sm">
                    <code className="bg-slate-950 px-2 py-1 rounded border border-slate-800 select-all block truncate">
                      {port.reconCommand}
                    </code>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </section>
    </div>
  );
};
